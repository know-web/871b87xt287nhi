-- Supabase setup schema for the HIT project.
-- Run once in the Supabase SQL Editor or apply as a migration.
-- Never store Supabase secret/service_role keys in this file or a client app.

create table public."HIT" (
  id_target bigint generated by default as identity primary key,
  target text not null check (length(btrim(target)) > 0),
  domain text generated always as (
    case
      when regexp_replace(
        split_part(
          split_part(
            split_part(
              regexp_replace(btrim(target), '^[a-z][a-z0-9+.-]*://', '', 'i'),
              '/', 1
            ),
            '?', 1
          ),
          '#', 1
        ),
        ':[0-9]+$', ''
      ) ~ '^[0-9.]+$'
      then ''
      else coalesce(
        (regexp_match(
          lower(regexp_replace(
            split_part(
              split_part(
                split_part(
                  regexp_replace(btrim(target), '^[a-z][a-z0-9+.-]*://', '', 'i'),
                  '/', 1
                ),
                '?', 1
              ),
              '#', 1
            ),
            ':[0-9]+$', ''
          )),
          '(\.[^.]+)$'
        ))[1],
        ''
      )
    end
  ) stored,
  type_hit text not null check (length(btrim(type_hit)) > 0),
  cms text not null default 'Unknown',
  date timestamptz not null default now()
);

-- Case/outer-whitespace insensitive duplicate prevention for target values.
create unique index hit_target_unique_ci
  on public."HIT" (lower(btrim(target)));

create table public."Status" (
  id bigint generated by default as identity primary key,
  id_target bigint not null unique
    references public."HIT" (id_target) on delete cascade,
  status text not null default 'OFFLINE'
    check (status in ('ONLINE', 'OFFLINE')),
  target_status_date timestamptz not null default now()
);

-- Every target gets one status row. Callers can then update it using Status.id.
create function public.create_initial_hit_status()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  insert into public."Status" (id_target, status)
  values (new.id_target, 'OFFLINE');
  return new;
end;
$$;

create trigger hit_create_initial_status
after insert on public."HIT"
for each row
execute function public.create_initial_hit_status();

-- Refresh the timestamp whenever the status row is updated.
create function public.set_hit_status_date()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.target_status_date := now();
  return new;
end;
$$;

create trigger hit_status_date_updated
before update on public."Status"
for each row
execute function public.set_hit_status_date();

revoke all on function public.create_initial_hit_status() from public, anon, authenticated, service_role;
revoke all on function public.set_hit_status_date() from public, anon, authenticated, service_role;

-- Keep both tables inaccessible to public and signed-in client roles.
-- The backend service_role may read Status and update only its status value.
-- It cannot read or mutate HIT through the Data API.
alter table public."HIT" enable row level security;
alter table public."Status" enable row level security;

revoke all on table public."HIT", public."Status"
  from public, anon, authenticated, service_role;

grant select on table public."Status" to service_role;
grant update (status) on table public."Status" to service_role;

-- Backfill status rows if this script is adapted for an existing HIT table.
insert into public."Status" (id_target, status)
select id_target, 'OFFLINE'
from public."HIT"
on conflict (id_target) do nothing;

